-- SafeVoice database schema for Supabase (PostgreSQL).
-- Safe to run more than once: everything uses IF NOT EXISTS / CREATE OR REPLACE.
-- Run it either with  "npm run db:setup"  (inside backend) or by pasting it into Supabase > SQL Editor > Run.

-- Timestamps are stored as ISO text ("2026-11-23T10:15:00.000Z"), exactly like the old SQLite version,
-- so the application code and the audit-log hash chain behave identically.
CREATE OR REPLACE FUNCTION sv_now() RETURNS text
  LANGUAGE sql STABLE AS
  $$ SELECT to_char(now() AT TIME ZONE 'utc', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"') $$;

CREATE TABLE IF NOT EXISTS users (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username      TEXT NOT NULL,                  -- NOT unique: only email and NID must be unique
  email         TEXT NOT NULL,
  password_hash TEXT NOT NULL,
  role          TEXT NOT NULL CHECK (role IN ('user','investigator','admin')),
  nid_enc       TEXT,           -- NID encrypted (AES-256-GCM): only admins can decrypt it through the admin portal
  nid_hash      TEXT UNIQUE,    -- keyed hash of the NID: enforces "one NID = one account" without reading it
  is_active     INTEGER NOT NULL DEFAULT 1,
  created_at    TEXT NOT NULL DEFAULT sv_now()
);
-- Emails are unique ignoring upper/lower case (same as the old COLLATE NOCASE).
CREATE UNIQUE INDEX IF NOT EXISTS users_email_key ON users (lower(email));
CREATE INDEX IF NOT EXISTS idx_users_username ON users (lower(username));

CREATE TABLE IF NOT EXISTS investigator_profiles (
  user_id        INTEGER PRIMARY KEY REFERENCES users(id),
  job_type       TEXT NOT NULL CHECK (job_type IN ('police','journalist')),
  details_enc    TEXT NOT NULL,  -- full name, organization, job title, work ID number (encrypted JSON)
  id_card_file   TEXT NOT NULL,  -- encrypted file on disk
  id_card_mime   TEXT NOT NULL,
  bio            TEXT NOT NULL DEFAULT '',
  status         TEXT NOT NULL DEFAULT 'unverified' CHECK (status IN ('unverified','verified')),
  verified_by    INTEGER REFERENCES users(id),
  verified_at    TEXT
);

CREATE TABLE IF NOT EXISTS sessions (
  id         TEXT PRIMARY KEY,
  user_id    INTEGER NOT NULL REFERENCES users(id),
  created_at TEXT NOT NULL,
  expires_at TEXT NOT NULL,
  ended_at   TEXT
);

CREATE TABLE IF NOT EXISTS reports (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     INTEGER NOT NULL REFERENCES users(id),
  type        TEXT NOT NULL,
  description TEXT NOT NULL,
  lat         DOUBLE PRECISION NOT NULL,
  lng         DOUBLE PRECISION NOT NULL,
  occurred_at TEXT NOT NULL,
  status      TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active','withdrawn','hidden')),
  created_at  TEXT NOT NULL DEFAULT sv_now(),
  updated_at  TEXT
);
CREATE INDEX IF NOT EXISTS idx_reports_status ON reports(status);
CREATE INDEX IF NOT EXISTS idx_reports_user ON reports(user_id);

CREATE TABLE IF NOT EXISTS chat_threads (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  report_id       INTEGER NOT NULL REFERENCES reports(id),
  investigator_id INTEGER NOT NULL REFERENCES users(id),
  reporter_id     INTEGER NOT NULL REFERENCES users(id),
  created_at      TEXT NOT NULL DEFAULT sv_now(),
  UNIQUE (report_id, investigator_id)
);

CREATE TABLE IF NOT EXISTS chat_messages (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  thread_id  INTEGER NOT NULL REFERENCES chat_threads(id),
  sender_id  INTEGER NOT NULL REFERENCES users(id),
  body_enc   TEXT NOT NULL,      -- message encrypted at rest
  created_at TEXT NOT NULL DEFAULT sv_now()
);
CREATE INDEX IF NOT EXISTS idx_messages_thread ON chat_messages(thread_id, id);

-- Files attached to chat messages. The file on disk is encrypted; the original file name is encrypted too.
CREATE TABLE IF NOT EXISTS chat_files (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  message_id  INTEGER NOT NULL UNIQUE REFERENCES chat_messages(id),
  thread_id   INTEGER NOT NULL REFERENCES chat_threads(id),
  stored_name TEXT NOT NULL,
  name_enc    TEXT NOT NULL,
  mime        TEXT NOT NULL,
  size        INTEGER NOT NULL,
  created_at  TEXT NOT NULL DEFAULT sv_now()
);
CREATE INDEX IF NOT EXISTS idx_chat_files_thread ON chat_files(thread_id);

-- Public attachments of crime reports (documents, PDFs, pictures, videos).
CREATE TABLE IF NOT EXISTS report_files (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  report_id   INTEGER NOT NULL REFERENCES reports(id),
  stored_name TEXT NOT NULL,
  mime        TEXT NOT NULL,
  size        INTEGER NOT NULL,
  created_at  TEXT NOT NULL DEFAULT sv_now()
);
CREATE INDEX IF NOT EXISTS idx_report_files_report ON report_files(report_id);

-- Last recorded location of each user (only the latest point is kept, no history).
CREATE TABLE IF NOT EXISTS user_locations (
  user_id    INTEGER PRIMARY KEY REFERENCES users(id),
  lat        DOUBLE PRECISION NOT NULL,
  lng        DOUBLE PRECISION NOT NULL,
  accuracy   DOUBLE PRECISION,
  updated_at TEXT NOT NULL
);

-- "A crime happened near you" alerts. One alert per user per report.
CREATE TABLE IF NOT EXISTS notifications (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     INTEGER NOT NULL REFERENCES users(id),
  report_id   INTEGER NOT NULL REFERENCES reports(id),
  distance_km DOUBLE PRECISION NOT NULL,
  created_at  TEXT NOT NULL DEFAULT sv_now(),
  read_at     TEXT,
  UNIQUE (user_id, report_id)
);
CREATE INDEX IF NOT EXISTS idx_notifications_user ON notifications(user_id, id);

-- Remembers, per person and chat, the last message they have read (used for unread counters).
CREATE TABLE IF NOT EXISTS chat_reads (
  thread_id    INTEGER NOT NULL REFERENCES chat_threads(id),
  user_id      INTEGER NOT NULL REFERENCES users(id),
  last_read_id INTEGER NOT NULL DEFAULT 0,
  PRIMARY KEY (thread_id, user_id)
);

-- Admin audit log. Each row is chained to the previous one by a hash (tamper-evident).
CREATE TABLE IF NOT EXISTS audit_logs (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ts              TEXT NOT NULL,
  admin_id        INTEGER NOT NULL,
  admin_username  TEXT NOT NULL,
  action          TEXT NOT NULL,
  target_type     TEXT,
  target_id       INTEGER,
  target_username TEXT,
  message         TEXT NOT NULL,
  ip              TEXT,
  prev_hash       TEXT NOT NULL,
  hash            TEXT NOT NULL
);

-- PERMANENT: the database itself refuses to change or delete these rows.
CREATE OR REPLACE FUNCTION sv_block_change() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION '% are permanent and cannot be modified or deleted', TG_ARGV[0];
END $$;

DROP TRIGGER IF EXISTS audit_no_update ON audit_logs;
DROP TRIGGER IF EXISTS audit_no_delete ON audit_logs;
DROP TRIGGER IF EXISTS chat_no_update  ON chat_messages;
DROP TRIGGER IF EXISTS chat_no_delete  ON chat_messages;
CREATE TRIGGER audit_no_update BEFORE UPDATE ON audit_logs   FOR EACH ROW EXECUTE FUNCTION sv_block_change('audit logs');
CREATE TRIGGER audit_no_delete BEFORE DELETE ON audit_logs   FOR EACH ROW EXECUTE FUNCTION sv_block_change('audit logs');
CREATE TRIGGER chat_no_update  BEFORE UPDATE ON chat_messages FOR EACH ROW EXECUTE FUNCTION sv_block_change('chat messages');
CREATE TRIGGER chat_no_delete  BEFORE DELETE ON chat_messages FOR EACH ROW EXECUTE FUNCTION sv_block_change('chat messages');

-- ---------------------------------------------------------------------------------------------
-- SECURITY (important on Supabase): Supabase publishes every table in the "public" schema through
-- its automatic REST API (reachable with the public "anon" key). SafeVoice never uses that API, only the
-- backend connects, so we switch Row Level Security ON with NO policies. That means the REST API can read
-- and write NOTHING. The backend's "postgres" connection bypasses RLS, so SafeVoice keeps working.
-- ---------------------------------------------------------------------------------------------
ALTER TABLE users                 ENABLE ROW LEVEL SECURITY;
ALTER TABLE investigator_profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE sessions              ENABLE ROW LEVEL SECURITY;
ALTER TABLE reports               ENABLE ROW LEVEL SECURITY;
ALTER TABLE chat_threads          ENABLE ROW LEVEL SECURITY;
ALTER TABLE chat_messages         ENABLE ROW LEVEL SECURITY;
ALTER TABLE chat_files            ENABLE ROW LEVEL SECURITY;
ALTER TABLE report_files          ENABLE ROW LEVEL SECURITY;
ALTER TABLE user_locations        ENABLE ROW LEVEL SECURITY;
ALTER TABLE notifications         ENABLE ROW LEVEL SECURITY;
ALTER TABLE chat_reads            ENABLE ROW LEVEL SECURITY;
ALTER TABLE audit_logs            ENABLE ROW LEVEL SECURITY;

-- Belt and braces: also take away the API roles' table permissions (only exist on Supabase).
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
    REVOKE ALL ON ALL TABLES IN SCHEMA public FROM anon;
    REVOKE ALL ON ALL SEQUENCES IN SCHEMA public FROM anon;
    REVOKE ALL ON ALL FUNCTIONS IN SCHEMA public FROM anon;
  END IF;
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
    REVOKE ALL ON ALL TABLES IN SCHEMA public FROM authenticated;
    REVOKE ALL ON ALL SEQUENCES IN SCHEMA public FROM authenticated;
    REVOKE ALL ON ALL FUNCTIONS IN SCHEMA public FROM authenticated;
  END IF;
END $$;
